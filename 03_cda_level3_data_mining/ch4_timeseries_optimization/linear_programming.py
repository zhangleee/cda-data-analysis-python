import warnings
warnings.filterwarnings("ignore")


############################################################
# ### 线性规划
############################################################


############################################################
# 模型样例
############################################################


############################################################
# Objective function:
#
# Maximize $x_1 + 2 x_2 + 3 x_3 + x_4$
############################################################


############################################################
# Subject To
#
# r1: $- x_1 + x_2 + x_3 + 10 x_4 <= 20$
#
# r2: $x_1 - 3 x_2 + x_3 <= 30$
#
# r3: $x_2 - 3.5 x_4  = 0$
############################################################


############################################################
# Bounds
#
# $0 <= x_1 <= 40$
#
# $2 <= x_4 <= 3$
############################################################


############################################################
# 导入CPLEX
############################################################

# --- 代码块 7 ---
import cplex


############################################################
# 初始化模型
############################################################

# --- 代码块 9 ---
op = cplex.Cplex()


############################################################
# 读取lp文件
############################################################

# --- 代码块 11 ---
op.read("productivity.lp")


############################################################
# 模型求解
############################################################

# --- 代码块 13 ---
op.solve()

# --- 代码块 14 ---
print("Max objective value is %s" %op.solution.get_objective_value())
print("Best Productivety is %s" %op.solution.get_values())
